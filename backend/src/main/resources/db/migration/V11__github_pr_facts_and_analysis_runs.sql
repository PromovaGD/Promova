CREATE TABLE github_pull_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_user_id BIGINT NOT NULL,
    evidence_id BIGINT,
    repository VARCHAR(255) NOT NULL,
    pull_number INTEGER NOT NULL,
    author_login VARCHAR(100),
    title VARCHAR(1000),
    state VARCHAR(30) NOT NULL,
    draft BOOLEAN NOT NULL,
    source_url VARCHAR(2048),
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    closed_at TIMESTAMP(6) WITH TIME ZONE,
    merged_at TIMESTAMP(6) WITH TIME ZONE,
    commit_count INTEGER,
    changed_files_count INTEGER,
    first_review_requested_at TIMESTAMP(6) WITH TIME ZONE,
    request_events_synced_at TIMESTAMP(6) WITH TIME ZONE,
    last_synced_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_github_facts_employee FOREIGN KEY (employee_user_id) REFERENCES users (id),
    CONSTRAINT fk_github_facts_evidence FOREIGN KEY (evidence_id) REFERENCES evidences (id),
    CONSTRAINT uk_github_facts_owner_repo_number UNIQUE (employee_user_id, repository, pull_number)
);

CREATE INDEX ix_github_facts_employee_created ON github_pull_requests (employee_user_id, created_at, id);

CREATE TABLE github_pull_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL,
    provider_review_id BIGINT NOT NULL,
    reviewer_login VARCHAR(100) NOT NULL,
    state VARCHAR(40) NOT NULL,
    submitted_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_github_pull_reviews_fact FOREIGN KEY (pull_request_id) REFERENCES github_pull_requests (id),
    CONSTRAINT uk_github_pull_reviews_provider UNIQUE (pull_request_id, provider_review_id)
);

CREATE INDEX ix_github_pull_reviews_first ON github_pull_reviews (pull_request_id, submitted_at, id);

CREATE TABLE analysis_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id BIGINT NOT NULL,
    analysis_id BIGINT,
    engine VARCHAR(40) NOT NULL,
    engine_version VARCHAR(80) NOT NULL,
    model VARCHAR(200),
    outcome VARCHAR(20) NOT NULL,
    error_type VARCHAR(120),
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_analysis_runs_evidence FOREIGN KEY (evidence_id) REFERENCES evidences (id) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_runs_analysis FOREIGN KEY (analysis_id) REFERENCES saved_analyses (id) ON DELETE SET NULL,
    CONSTRAINT ck_analysis_runs_outcome CHECK (outcome IN ('SUCCEEDED', 'FAILED'))
);

CREATE INDEX ix_analysis_runs_evidence_started ON analysis_runs (evidence_id, started_at, id);

CREATE TABLE analysis_suggestions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id BIGINT NOT NULL,
    ordinal INTEGER NOT NULL,
    suggestion_text VARCHAR(200) NOT NULL,
    category VARCHAR(80),
    severity VARCHAR(20),
    taxonomy_version VARCHAR(80),
    CONSTRAINT fk_analysis_suggestions_analysis FOREIGN KEY (analysis_id) REFERENCES saved_analyses (id) ON DELETE CASCADE,
    CONSTRAINT uk_analysis_suggestions_order UNIQUE (analysis_id, ordinal)
);

CREATE INDEX ix_analysis_suggestions_category ON analysis_suggestions (category, severity);
