    id BIGINT PRIMARY KEY,
    manager_label VARCHAR(80) NOT NULL,
    employee_label VARCHAR(80) NOT NULL,
    job_role_label VARCHAR(80) NOT NULL,
    level_label VARCHAR(80) NOT NULL,
    characteristics_label VARCHAR(80) NOT NULL,
    objective_label VARCHAR(80) NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

