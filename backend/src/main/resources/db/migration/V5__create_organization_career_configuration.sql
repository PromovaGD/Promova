CREATE TABLE job_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_job_roles_name UNIQUE (name),
    CONSTRAINT ck_job_roles_status CHECK (status IN ('ACTIVE', 'ARCHIVED'))
);

CREATE TABLE job_role_levels (
    job_role_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL,
    level_id VARCHAR(40) NOT NULL,
    PRIMARY KEY (job_role_id, sort_order),
    CONSTRAINT uk_job_role_levels_level UNIQUE (job_role_id, level_id),
    CONSTRAINT fk_job_role_levels_role FOREIGN KEY (job_role_id) REFERENCES job_roles (id)
);

