CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_user_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_teams_manager FOREIGN KEY (manager_user_id) REFERENCES users (id)
);

CREATE TABLE team_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL,
    employee_user_id BIGINT NOT NULL,
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_team_memberships_team FOREIGN KEY (team_id) REFERENCES teams (id),
    CONSTRAINT fk_team_memberships_employee FOREIGN KEY (employee_user_id) REFERENCES users (id),
    CONSTRAINT ck_team_memberships_dates CHECK (ended_at IS NULL OR ended_at > started_at)
);

CREATE INDEX ix_teams_manager ON teams (manager_user_id, id);
CREATE INDEX ix_team_memberships_employee ON team_memberships (employee_user_id, ended_at, team_id);
CREATE INDEX ix_team_memberships_team ON team_memberships (team_id, ended_at, employee_user_id);

-- Preserve the legacy visibility of existing employees during the migration.
INSERT INTO teams (manager_user_id, name, created_at)
SELECT id, 'Equipe principal', CURRENT_TIMESTAMP FROM users WHERE role = 'MANAGER';

INSERT INTO team_memberships (team_id, employee_user_id, started_at)
SELECT t.id, u.id, CURRENT_TIMESTAMP
FROM teams t CROSS JOIN users u
WHERE u.role = 'EMPLOYEE';

CREATE TABLE career_objective_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objective_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    target_date DATE,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_objective_events_objective FOREIGN KEY (objective_id) REFERENCES career_objectives (id),
    CONSTRAINT fk_objective_events_actor FOREIGN KEY (actor_user_id) REFERENCES users (id),
    CONSTRAINT ck_objective_events_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'ARCHIVED'))
);

CREATE INDEX ix_objective_events_objective ON career_objective_events (objective_id, occurred_at, id);

